#!/usr/bin/env python3
"""Regenerate every constant in anemos/base64/ that the suite trusts.

The suite must not trust the implementation it tests, so:
  - the reverse-alphabet table in base64.c comes from here;
  - the expected strings in test_base64.c come from Python's base64, an
    independent implementation (the first seven entries additionally match
    RFC 4648 §10's published vectors);
  - the golden messages are an LCG stream — x = (1103515245*x + 12345)
    mod 2^31, byte = (x >> 16) & 0xFF, seeded x = 1 — reproducible in
    Python and in C alike, so the suite needs no 1000-byte literal.

usage: python3 vectors.py        (prints C initialisers)
"""
import base64

ALPHABET = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"


def lcg_bytes(n: int) -> bytes:
    x = 1
    out = bytearray()
    for _ in range(n):
        x = (1103515245 * x + 12345) & 0x7FFFFFFF
        out.append((x >> 16) & 0xFF)
    return bytes(out)


def c_string(s: str, indent: str = "      ") -> str:
    """One C string literal, wrapped at 72 columns as adjacent literals."""
    lines = [f'"{s[i:i + 72]}"' for i in range(0, len(s), 72)]
    return ("\n" + indent).join(lines) if lines else '""'


def main() -> None:
    print("/* generated by vectors.py — reverse alphabet, 0xff = invalid */")
    rev = [0xFF] * 256
    for i, c in enumerate(ALPHABET):
        rev[c] = i
    print("static const uint8_t k_rev[256] = {")
    for row in range(0, 256, 8):
        print("    " + ", ".join(f"0x{v:02x}" for v in rev[row:row + 8]) + ",")
    print("};")
    print()

    cases = [
        ("rfc_empty", b"", ""),
        ("rfc_f", b"f", "Zg=="),
        ("rfc_fo", b"fo", "Zm8="),
        ("rfc_foo", b"foo", "Zm9v"),
        ("rfc_foob", b"foob", "Zm9vYg=="),
        ("rfc_fooba", b"fooba", "Zm9vYmE="),
        ("rfc_foobar", b"foobar", "Zm9vYmFy"),
    ]
    for n in (64, 255, 1000):
        cases.append((f"lcg_{n}", lcg_bytes(n), base64.b64encode(lcg_bytes(n)).decode()))

    print("/* expected strings; message bytes are regenerated in C (LCG) or")
    print(" * spelled out for the RFC cases */")
    for name, msg, enc in cases:
        text = "NULL" if name.startswith("lcg_") else f'"{msg.decode()}"'
        print(f'    {{ "{name}", {len(msg)}, {text},')
        print(f"      {c_string(enc)} }},")
    print()

    print("/* messages for the RFC cases */")
    for name, msg, _ in cases:
        if not name.startswith("lcg_"):
            print(f'/* {name}: {msg!r} */')


if __name__ == "__main__":
    main()
