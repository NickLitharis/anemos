#!/usr/bin/env python3
"""Regenerate every constant in anemos/crc32/ that the suite trusts.

The suite must not trust the implementation it tests, so both the lookup
table in crc32.c and the expected values in test_crc32.c come from here:
the table from the polynomial (0xEDB88320, reflected), the expected values
from Python's zlib — an independent CRC-32. The values for "a" and "abc"
are the widely-published ones and can be cross-checked by eye.

Golden messages are the shared LCG stream — x = (1103515245*x + 12345)
mod 2^31, byte = (x >> 16) & 0xFF, seeded x = 1 — reproducible in Python
and in C alike.

usage: python3 vectors.py        (prints C initialisers)
"""
import zlib

POLY = 0xEDB88320


def table() -> list[int]:
    out = []
    for i in range(256):
        c = i
        for _ in range(8):
            c = (c >> 1) ^ (POLY if c & 1 else 0)
        out.append(c)
    return out


def lcg_bytes(n: int) -> bytes:
    x = 1
    out = bytearray()
    for _ in range(n):
        x = (1103515245 * x + 12345) & 0x7FFFFFFF
        out.append((x >> 16) & 0xFF)
    return bytes(out)


def main() -> None:
    t = table()
    print("/* generated by vectors.py */")
    print("static const uint32_t k_table[256] = {")
    for row in range(0, 256, 4):
        cells = ", ".join(f"0x{t[j]:08x}u" for j in range(row, row + 4))
        print(f"    {cells},")
    print("};")
    print()

    text_cases = [
        ("empty", b""),
        ("a", b"a"),
        ("abc", b"abc"),
        ("message digest", b"message digest"),
        ("alpha", b"abcdefghijklmnopqrstuvwxyz"),
        ("alnum", b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"),
    ]
    for name, data in text_cases:
        crc = zlib.crc32(data) & 0xFFFFFFFF
        text = "NULL" if not data else f'"{data.decode()}"'
        print(f'    {{ "{name}", {len(data):>7}, 0x{crc:08x}u, PAT_TEXT, {text} }},')
    print(f'    {{ "digits10x8",  {80}, 0x{(zlib.crc32(b"1234567890" * 8) & 0xFFFFFFFF):08x}u, PAT_DIGITS, NULL }},')
    for n in (55, 56, 63, 64, 65):
        crc = zlib.crc32(b"x" * n) & 0xFFFFFFFF
        print(f'    {{ "{n}_bytes", {n:>4}, 0x{crc:08x}u, PAT_X, NULL }},')
    seq_crc = zlib.crc32(bytes(range(255))) & 0xFFFFFFFF
    print(f'    {{ "255_bytes", {255:>4}, 0x{seq_crc:08x}u, PAT_SEQ, NULL }},')
    ff_crc = zlib.crc32(b"\xff" * 100) & 0xFFFFFFFF
    print(f'    {{ "binary_ff", {100:>4}, 0x{ff_crc:08x}u, PAT_FF, NULL }},')
    zero_crc = zlib.crc32(b"\x00" * 64) & 0xFFFFFFFF
    print(f'    {{ "nul_bytes", {64:>4}, 0x{zero_crc:08x}u, PAT_ZERO, NULL }},')
    for n in (64, 255, 1000):
        crc = zlib.crc32(lcg_bytes(n)) & 0xFFFFFFFF
        print(f'    {{ "lcg_{n}", {n:>5}, 0x{crc:08x}u, PAT_LCG, NULL }},')


if __name__ == "__main__":
    main()
