#!/usr/bin/env python3
"""Turn the guest-side probe dump into table.c, or refuse to.

Input: sdos.bin — a stream of 12-byte little-endian (first, count, dos)
triples written by sdos_probe.c inside the XP guest.

Validation before anything is generated, because a table built from a bad
dump is silently wrong forever after:
  - the file size is a whole number of triples;
  - the runs tile [0, 2^32) exactly: first run starts at 0, each run starts
    where the previous ended, the last ends at 2^32;
  - independent anchors: a handful of status -> error pairs that are
    published facts about Windows (0 -> 0, ACCESS_DENIED -> 5, ...). If the
    dump disagrees with any anchor, the probe or the guest is wrong.

usage: gen_table.py <sdos.bin> <table.c>
"""
import struct
import sys

# Published, independent anchors — if the dump disagrees with any of these,
# the extraction is broken and no table is written.
ANCHORS = {
    0x00000000: 0,      # STATUS_SUCCESS           -> ERROR_SUCCESS
    0xC0000005: 998,    # STATUS_ACCESS_VIOLATION  -> ERROR_NOACCESS
    0xC0000017: 8,      # STATUS_NO_MEMORY         -> ERROR_NOT_ENOUGH_MEMORY
    0xC0000022: 5,      # STATUS_ACCESS_DENIED     -> ERROR_ACCESS_DENIED
    0xC0000023: 122,    # STATUS_BUFFER_TOO_SMALL  -> ERROR_INSUFFICIENT_BUFFER
    0xC0000034: 2,      # STATUS_OBJECT_NAME_NOT_FOUND -> ERROR_FILE_NOT_FOUND
    0xC000003A: 2,      # STATUS_OBJECT_PATH_NOT_FOUND -> ERROR_FILE_NOT_FOUND
    0xC000000D: 87,     # STATUS_INVALID_PARAMETER -> ERROR_INVALID_PARAMETER
    0xC000013A: 1223,   # STATUS_CONTROL_C_EXIT    -> ERROR_OPERATION_ABORTED
}


def load(path: str) -> list[tuple[int, int, int]]:
    data = open(path, "rb").read()
    if len(data) % 12:
        raise SystemExit(f"refusing: {len(data)} bytes is not a whole number of triples")
    runs = []
    for i in range(0, len(data), 12):
        first, count, dos = struct.unpack_from("<III", data, i)
        runs.append((first, count, dos))
    return runs


def validate(runs: list[tuple[int, int, int]]) -> None:
    if not runs:
        raise SystemExit("refusing: empty dump")
    if runs[0][0] != 0:
        raise SystemExit(f"refusing: first run starts at 0x{runs[0][0]:08x}, not 0")
    covered = 0
    for first, count, dos in runs:
        if count == 0:
            raise SystemExit(f"refusing: zero-length run at 0x{first:08x}")
        if first != covered:
            raise SystemExit(f"refusing: gap/overlap at 0x{covered:08x} (run starts 0x{first:08x})")
        covered += count
    if covered != 1 << 32:
        raise SystemExit(f"refusing: runs cover 0x{covered:x} of 0x100000000"
                         " — the probe was cut off mid-run")
    # anchors may fall inside a run, not only on its start: resolve by walking
    dos_by_status = {}
    for first, count, dos in runs:
        for status in (s for s in ANCHORS if first <= s < first + count):
            dos_by_status[status] = dos
    for status, want in sorted(ANCHORS.items()):
        got = dos_by_status.get(status)
        if got != want:
            raise SystemExit(f"refusing: anchor 0x{status:08x} -> {got}, expected {want}"
                             " (the dump disagrees with published Windows behaviour)")


def emit(runs: list[tuple[int, int, int]], out_path: str) -> None:
    with open(out_path, "w") as f:
        f.write("/* Generated by gen_table.py from the XP guest's own answers —\n"
                " * see statusdos.h. Do not edit; regenerate from the dump. */\n")
        f.write('#include "statusdos.c.h"\n\n')
        f.write(f"const uint32_t k_run_count = {len(runs)};\n\n")
        f.write("const struct AnemStatusDosRun k_runs[] = {\n")
        for first, _, dos in runs:
            f.write(f"    {{ 0x{first:08x}u, 0x{dos:08x}u }},\n")
        f.write("};\n")


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    runs = load(sys.argv[1])
    validate(runs)
    emit(runs, sys.argv[2])
    total_statuses = sum(c for _, c, _ in runs)
    print(f"ok: {len(runs)} runs, {total_statuses} statuses, "
          f"table {len(runs) * 8} bytes -> {sys.argv[2]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
