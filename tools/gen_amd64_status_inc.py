#!/usr/bin/env python3
"""Generate STATUS_* assembler equates for the AMD64 .asm sources.

Why this exists
---------------
The x64 kernel .asm files use STATUS_* constants (capture.asm compares against
STATUS_UNWIND_CONSOLIDATE, and friends). They get them by including
ksamd64.inc -> kxamd64.inc. But in this leak kxamd64.inc carries only 4 equate
definitions -- no STATUS_* at all -- while the i386 counterpart ks386.inc defines
40 of them.

So the AMD64 assembly does not build as shipped. The kernel's C sources are fine;
the assembler-side constant table simply never landed.

This script emits the missing table from public/sdk/inc/ntstatus.h, which is the
single source of truth for the values, and which the C side already uses. We
derive rather than hand-copy so the equates cannot drift from the headers.

Output is build/tmp and not checked in; rebuild it with:
    python3 tools/gen_amd64_status_inc.py > /tmp/ksamd64status.inc
"""
import re
import sys
from pathlib import Path

TREE = Path(__file__).resolve().parent.parent / "Source/XPSP1/NT"
NTSTATUS = TREE / "public/sdk/inc/ntstatus.h"

# Only the symbols the AMD64 assembly actually references; a broad dump would
# add names that collide with the assembler's own keywords.
def wanted_symbols():
    names = set()
    for pattern in ("base/ntos/*/amd64/*.asm", "base/hals/*/amd64/*.asm",
                    "base/ntos/*/amd64/*.inc", "base/hals/*/amd64/*.inc"):
        for f in TREE.glob(pattern):
            text = f.read_text(errors="ignore")
            names.update(re.findall(r"\bSTATUS_[A-Z0-9_]+\b", text))
    return names


def parse_ntstatus():
    text = NTSTATUS.read_text(errors="ignore")
    # #define STATUS_FOO ((NTSTATUS)0xC0000005L)
    pat = re.compile(r"^#define\s+(STATUS_[A-Z0-9_]+)\s+\(\(NTSTATUS\)\s*(0[xX][0-9A-Fa-f]+)L?\)", re.M)
    return dict(pat.findall(text))


def main():
    values = parse_ntstatus()
    need = wanted_symbols()
    have = sorted(s for s in need if s in values)
    missing = sorted(s for s in need if s not in values)

    print("; Generated by tools/gen_amd64_status_inc.py -- do not edit.")
    print("; STATUS_* equates for AMD64 assembly, derived from public/sdk/inc/ntstatus.h.")
    print("; The shipped kxamd64.inc omits these; i386 kss386.inc defines 40 of them.")
    print()
    for name in have:
        raw = int(values[name], 16)
        # MASM rejects a hex literal whose first character is a letter: `C0000005H`
        # is parsed as a symbol and fails with the misleading "redefinition" error.
        # A leading zero (`0C0000005H`) forces numeric parsing. ks386.inc does the
        # same thing, which is why its values look 9 digits wide.
        digits = f"{raw:08X}"
        if digits[0].isalpha():
            digits = "0" + digits
        print(f"{name} equ {digits}H")
    print()
    print(f"; {len(have)} symbols emitted, {len(missing)} missing from ntstatus.h", file=sys.stderr)
    if missing:
        print("; MISSING: " + " ".join(missing), file=sys.stderr)


if __name__ == "__main__":
    main()
