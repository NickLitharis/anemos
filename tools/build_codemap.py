#!/usr/bin/env python3
"""Build a full codebase map + per-file dependency report from graft's graph.

graft writes a complete graph to <root>/graft/.graph/wiring.json:
  nodes: {id, name, kind, path, span, signature, exported, ...}
  edges: {source, target, relation: "imports"|"calls", confidence}

This script turns that into:

  CODEMAP.md                      overview: directory rollup + hot symbols
  codemap/file_<path>.md          per-file: what it imports, defines,
                                  calls out to, and who calls in
  codemap/deps.tsv                one row per file: imports|defines|calls_out|called_by
  codemap/deps.json               the same, machine readable

Usage:
  python3 tools/build_codemap.py [--graph PATH] [--out DIR]
"""

from __future__ import annotations

import argparse
import collections
import json
import os
import re
import sys
from pathlib import Path

DEFAULT_GRAPH = "/tmp/xpgraph/graft/.graph/wiring.json"
DEFAULT_OUT = "docs/codemap"


def load(path: Path) -> dict:
    with path.open() as fh:
        return json.load(fh)


def build(graph: dict) -> dict:
    nodes = {n["id"]: n for n in graph["nodes"]}
    files = {i: n for i, n in nodes.items() if n["kind"] == "file"}

    # symbol -> owning file (nearest path prefix that is a file node)
    sym_owner: dict[str, str] = {}
    for nid, n in nodes.items():
        if n["kind"] == "file":
            continue
        p = n.get("path")
        if p and p in files:
            sym_owner[nid] = p

    imports_out = collections.defaultdict(set)
    calls_out = collections.defaultdict(set)   # file -> set((target_file, symbol))
    calls_in = collections.defaultdict(set)    # file -> set((source_file, symbol))

    for e in graph["edges"]:
        src, tgt, rel = e["source"], e["target"], e["relation"]
        if rel == "imports":
            if src in files and tgt in files:
                imports_out[src].add(tgt)
        elif rel == "calls":
            sf = src if src in files else sym_owner.get(src)
            tf = tgt if tgt in files else sym_owner.get(tgt)
            if sf and tf:
                calls_out[sf].add((tf, nodes.get(tgt, {}).get("name", tgt)))
                calls_in[tf].add((sf, nodes.get(tgt, {}).get("name", tgt)))

    defines = collections.defaultdict(list)
    for nid, f in sym_owner.items():
        n = nodes[nid]
        if n["kind"] in ("function", "type", "class"):
            defines[f].append((n["name"], n["kind"], n.get("span") or ""))

    per_file = {}
    for f in sorted(files):
        per_file[f] = {
            "imports": sorted(imports_out.get(f, ())),
            "defines": sorted(defines.get(f, ())),
            "calls_out": sorted(calls_out.get(f, ())),
            "called_by": sorted(calls_in.get(f, ())),
        }

    # who is called from the most distinct files -> the real core
    fan_in = collections.Counter()
    for f, targets in calls_out.items():
        for tf, sym in targets:
            fan_in[sym] += 1

    return {"per_file": per_file, "fan_in": fan_in, "nodes": nodes, "files": files}


def rollup(per_file: dict) -> list[tuple[str, int, int, int]]:
    rows = collections.defaultdict(lambda: [0, 0, 0])
    for f, d in per_file.items():
        top = f.split("/")[1] if f.count("/") > 1 else "(root)"
        rows[top][0] += 1
        rows[top][1] += len(d["imports"])
        rows[top][2] += len(d["defines"])
    return sorted(((k, *v) for k, v in rows.items()), key=lambda r: -r[1])


def write_overview(out: Path, res: dict) -> None:
    pf, fan_in, files = res["per_file"], res["fan_in"], res["files"]
    lines = ["# XP kernel code map", "",
             "Generated by `tools/build_codemap.py` from graft's wiring graph.", ""]
    lines += ["## Directory rollup", "",
              "| directory | files | import edges | symbols defined |",
              "|---|---:|---:|---:|"]
    for name, nf, ni, nd in rollup(pf):
        lines.append(f"| `{name}` | {nf} | {ni} | {nd} |")
    lines += ["", f"**Totals:** {len(files)} files, "
                  f"{sum(len(d['imports']) for d in pf.values())} import edges, "
                  f"{sum(len(d['defines']) for d in pf.values())} symbols.", ""]

    lines += ["## Most-referenced symbols (the actual core surface)", "",
              "Ranked by the number of distinct files that call them. These are the",
              "symbols a shim has to get right first.", "",
              "| symbol | called from N files |", "|---|---:|"]
    for sym, n in fan_in.most_common(40):
        lines.append(f"| `{sym}` | {n} |")
    lines.append("")

    heavy = sorted(pf.items(), key=lambda kv: -len(kv[1]["imports"]))[:25]
    lines += ["## Files with the widest dependency footprint", "",
              "| file | imports | calls out | called by |", "|---|---:|---:|---:|"]
    for f, d in heavy:
        lines.append(f"| `{f}` | {len(d['imports'])} | {len(d['calls_out'])} | {len(d['called_by'])} |")
    lines.append("")
    (out / "CODEMAP.md").write_text("\n".join(lines))


def write_per_file(out: Path, res: dict) -> None:
    pf = res["per_file"]
    fdir = out / "files"
    fdir.mkdir(parents=True, exist_ok=True)
    for f, d in pf.items():
        name = re.sub(r"[^A-Za-z0-9._-]", "_", f.replace("/", "__")) + ".md"
        L = [f"# {f}", ""]
        L += [f"**imports {len(d['imports'])}** · "
              f"**defines {len(d['defines'])}** · "
              f"**calls out {len(d['calls_out'])}** · "
              f"**called by {len(d['called_by'])}**", ""]
        if d["imports"]:
            L += ["## Includes / imports", ""]
            L += [f"- `{i}`" for i in d["imports"]]
            L.append("")
        if d["defines"]:
            L += ["## Defines", ""]
            L += [f"- `{s}` ({k}) {sp}" for s, k, sp in d["defines"]]
            L.append("")
        if d["calls_out"]:
            L += ["## Calls out to", ""]
            L += [f"- `{s}` in `{tf}`" for tf, s in d["calls_out"]]
            L.append("")
        if d["called_by"]:
            L += ["## Called by", ""]
            L += [f"- `{s}` from `{sf}`" for sf, s in d["called_by"]]
            L.append("")
        (fdir / name).write_text("\n".join(L))


def write_tables(out: Path, res: dict) -> None:
    pf = res["per_file"]
    tsv = ["file\timports\tdefines\tcalls_out\tcalled_by"]
    for f, d in pf.items():
        tsv.append(f"{f}\t{len(d['imports'])}\t{len(d['defines'])}\t"
                   f"{len(d['calls_out'])}\t{len(d['called_by'])}")
    (out / "deps.tsv").write_text("\n".join(tsv) + "\n")
    js = {f: {"imports": d["imports"],
              "defines": [[s, k, sp] for s, k, sp in d["defines"]],
              "calls_out": [[tf, s] for tf, s in d["calls_out"]],
              "called_by": [[sf, s] for sf, s in d["called_by"]]}
          for f, d in pf.items()}
    (out / "deps.json").write_text(json.dumps(js, indent=1))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--graph", default=DEFAULT_GRAPH)
    ap.add_argument("--out", default=DEFAULT_OUT)
    a = ap.parse_args()

    gp = Path(a.graph)
    if not gp.is_file():
        print(f"graph not found: {gp}\nrun: cd /tmp/xpgraph && graft build .", file=sys.stderr)
        return 2
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)

    res = build(load(gp))
    write_overview(out, res)
    write_per_file(out, res)
    write_tables(out, res)

    pf = res["per_file"]
    print(f"files: {len(pf)}")
    print(f"import edges: {sum(len(d['imports']) for d in pf.values())}")
    print(f"call edges: {sum(len(d['calls_out']) for d in pf.values())}")
    print(f"wrote {out}/CODEMAP.md, {out}/deps.tsv, {out}/deps.json, "
          f"{len(list((out/'files').iterdir()))} per-file pages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
